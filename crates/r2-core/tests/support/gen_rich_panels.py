"""Generate rich-15 panel vectors for r2 R1 renderer tests (error_panel, hex_panel)."""
import io, sys
from rich.console import Console
from c2.console import render
from c2.core.errors import ConsoleError

def rendered(renderable, width):
    buf = io.StringIO()
    Console(file=buf, force_terminal=False, width=width).print(renderable)
    out = buf.getvalue()
    assert out.endswith("\n")
    return out[:-1]

def rs(s):
    # Rust string literal (escape \ " and control chars)
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f: out.append("\\u{%x}" % ord(ch))
        else: out.append(ch)
    return '"' + "".join(out) + '"'

