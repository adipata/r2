# Caret rows laid out by rich (`caret_text`'s Text: row + "\n" + spaces + "^") with r2's
# column (§11 D14): the cell width of the tab-expanded, control-stripped row prefix.
carets = [
    ("load mem xx", 9),
    ("a\tb:#zz", 2),
    ("load\tmem x", 9),
    ("key info e\u0301x", 12),
    ("abc\rdef", 5),
    ("\t\tx", 2),
    ("ab\tc\td", 5),
    ("load mem aes " + "ab " * 40 + "zz", 133),
    ("key info \u65e5\u672c x", 16),
]
cwidths = [80, 200, 40]
print("/// (line, byte offset, console width, rich output)")
print("pub const CARETS: &[(&str, usize, usize, &str)] = &[")
for line, pos in carets:
    row_start = line.rfind("\n", 0, pos) + 1
    row_end = line.find("\n", pos)
    if row_end < 0:
        row_end = len(line)
    prefix = Text(line[row_start:pos])
    prefix.expand_tabs(8)
    text = Text(line[row_start:row_end])
    text.append("\n" + " " * cell_len(prefix.plain))
    text.append("^", style="bold red")
    for w in cwidths:
        out = rendered(text, w)
        print(f"    ({rs(line)}, {len(line[:pos].encode())}, {w}, {rs(out)}),")
print("];")

# rich `cell_len` of single code points (every CELL_WIDTHS range start/end and the code point
# after it) and of grapheme sequences — pinned through the caret column.
table = load_cell_table("latest")
points = set()
for start, end, _ in table.widths:
    for cp in (start, end, end + 1, max(start - 1, 0)):
        points.add(cp)
for c in table.narrow_to_wide:
    points.add(ord(c))
points.update(range(0x80, 0xB0))
skip = {0x0A, 0x0D, 0x07, 0x08, 0x0B, 0x0C}
samples = [chr(cp) for cp in sorted(points) if cp <= 0x10FFFF and not (0xD800 <= cp <= 0xDFFF) and cp not in skip]
samples += [chr(ord(c)) + "\ufe0f" for c in sorted(table.narrow_to_wide)[:40]]
samples += [
    "\U0001f469\u200d\U0001f4bb", "\U0001f468\u200d\U0001f469\u200d\U0001f467", "\u2764\ufe0f",
    "\U0001f1eb\U0001f1f7", "\U0001f44d\U0001f3fd", "a\u200db", "\u200da", "a\u200d", "\ufe0fa",
    "\u200d\u200d", "#\ufe0f\u20e3", "\u0928\u092e\u0938\u094d\u0924\u0947", "e\u0301", "\u00ad",
    "a\tb", "\t", "ab\tc\td", "\u65e5\t\u672c",
]
print("/// (text, rich `cell_len` after rich's own tab expansion)")
print("#[rustfmt::skip]")
print("pub const CELL_LENS: &[(&str, usize)] = &[")
for t in samples:
    expanded = Text(t)
    expanded.expand_tabs(8)
    print(f"    ({rs(t)}, {cell_len(expanded.plain)}),")
print("];")
