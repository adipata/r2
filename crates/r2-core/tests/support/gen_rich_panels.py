def rendered(renderable, width):
    buf = io.StringIO()
    Console(file=buf, force_terminal=False, width=width).print(renderable)
    out = buf.getvalue()
    assert out.endswith("\n")
    return out[:-1]

def rendered_str(text, width, emoji=True, highlight=True):
    buf = io.StringIO()
    Console(file=buf, force_terminal=False, width=width).print(
        text, markup=False, emoji=emoji, highlight=highlight
    )
    out = buf.getvalue()
    assert out.endswith("\n")
    return out[:-1]

def rs(s):
    # Rust string literal (escape \ " and control chars)
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7f: out.append("\\u{%x}" % ord(ch))
        # invisible / combining / format / separator code points as escapes (bidi controls
        # would trip rustc's text_direction_codepoint_in_literal lint)
        elif ord(ch) > 0x7f and unicodedata.category(ch)[0] in "MCZ": out.append("\\u{%x}" % ord(ch))
        else: out.append(ch)
    return '"' + "".join(out) + '"'

