print("pub const ERROR_PANELS: &[(&str, Option<&str>, usize, &str)] = &[")
for msg, hint in errors:
    for w in widths:
        out = rendered(render.error_panel(ConsoleError(msg, hint=hint)), w)
        print(f"    ({rs(msg)}, {('Some(' + rs(hint) + ')') if hint is not None else 'None'}, {w}, {rs(out)}),")
print("];")

